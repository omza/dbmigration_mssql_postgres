CREATE view [stage].[wilken_jahresprognosen_letzte] as

	with jahresverbraeuche_raw as (

		SELECT 
			ZPT_ID,
			ZPTEM_ZEITRAUMVON, 
			ZPTEM_ZEITRAUMBIS, 
			SUM(CASE WHEN ZPTMA_VERBRAUCHBER IS NULL THEN 0 ELSE ZPTMA_VERBRAUCHBER END) AS ZPTEM_VERBRAUCHBER, 

			SUM(CASE WHEN ZPTMA_JAHRESVERBRAUCHBER IS NULL THEN 0 ELSE ZPTMA_JAHRESVERBRAUCHBER END) AS ZPTEM_JAHRESVERBRAUCHBER,


			SUM(CASE 
					WHEN ZPTMA_VERBRAUCHBER IS NULL THEN 0 
					ELSE CASE 
							WHEN ENZPTMA.VBA_NR IN('1002','1005','10051') THEN ZPTMA_VERBRAUCHBER 
							ELSE 0 
						END 
				END) AS ZPTEM_VERBRAUCHBER_NT,

			SUM(CASE 
					WHEN ZPTMA_JAHRESVERBRAUCHBER IS NULL THEN 0 
					ELSE CASE 
							WHEN ENZPTMA.VBA_NR IN('1002','1005','10051') THEN ZPTMA_JAHRESVERBRAUCHBER 
							ELSE 0 
						END 
				END) AS ZPTEM_JAHRESVERBRAUCHBER_NT

/*

	NT VBAs sind ENZPTMA.VBA_NR IN(
'1002',
'1005',
'10051')


*/

		FROM 
			raw.wilken_enzptma ENZPTMA with (nolock), 
			raw.wilken_enzptem ENZPTEM with (nolock)

		WHERE 
			ENZPTMA.ZPTEM_ID = ENZPTEM.ZPTEM_ID
			--and ENZPTEM.ZPT_ID = 173
			--AND GETDATE() between ZPTEM_ZEITRAUMVON and ZPTEM_ZEITRAUMBIS
			and ZPTEM_ZEITRAUMVON >= convert(date, '01.01.1999', 104)
			AND ENZPTEM.ZPTEM_ART = 0
			AND ENZPTEM.PRZ_ID NOT IN('5')
			AND ENZPTMA.VBA_NR IN(
			'2001',
			'2004',
			'20050',
			'1001',
			'1004',
			'1002',
			'1005',
			'10050',
			'10051')
		
		GROUP BY 
			ZPT_ID, 
			ZPTEM_ZEITRAUMVON, 
			ZPTEM_ZEITRAUMBIS

	),
	
	jahresprognosen_gewichtet as (
		SELECT
			ZPT_ID, 
			ZPTEM_ZEITRAUMVON, 
			ZPTEM_ZEITRAUMBIS, 
			ZPTEM_VERBRAUCHBER, 
			ZPTEM_JAHRESVERBRAUCHBER, 
			ZPTEM_VERBRAUCHBER_NT,
			ZPTEM_JAHRESVERBRAUCHBER_NT,
			CASE
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 0 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 1
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 1 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 2
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 2 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 3
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 3 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 4
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 4 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 5
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 5 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 6
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 6 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 7
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 7 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 8
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 8 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 9
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 9 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 10
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 10 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 11
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 11 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 12
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 12 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 13
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 13 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 14
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 14 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 15
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 15 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 16
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 16 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 17
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 17 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 18
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 18 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 19
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 19 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 20
				WHEN SUM(DATEDIFF(DAY, ZPTEM_ZEITRAUMVON, ZPTEM_ZEITRAUMBIS+1)) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 20 PRECEDING AND 0 PRECEDING) BETWEEN 355 AND 375 THEN 21
			ELSE 99 
			END AS ANZAHL_BIS_365
		FROM 
			jahresverbraeuche_raw jv
	),

	jahresprognose_kumuliert as (

		SELECT
			ZPT_ID, 
			ZPTEM_ZEITRAUMVON AS PROG_BEGINN, 
			ZPTEM_ZEITRAUMBIS AS PROG_ENDE, 
			ANZAHL_BIS_365,
			CASE WHEN ANZAHL_BIS_365 = 99 THEN 'PROG_WERT' ELSE 'ABR_365' END AS PROGNOSEDATEN_TYP,
			CASE 
				WHEN ANZAHL_BIS_365 = 99 
				THEN ZPTEM_JAHRESVERBRAUCHBER 
				ELSE SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN CURRENT ROW AND CURRENT ROW) 
			END AS PROGNOSE_SUMME_365,

			CASE 
				WHEN ANZAHL_BIS_365 = 99 
				THEN ZPTEM_JAHRESVERBRAUCHBER_NT 
				ELSE SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN CURRENT ROW AND CURRENT ROW) 
			END AS PROGNOSE_SUMME_365_NT,

			CASE
				WHEN ANZAHL_BIS_365 = 1 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 0 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 2 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 1 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 3 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 2 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 4 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 3 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 5 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 4 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 6 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 5 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 7 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 6 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 8 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 7 PRECEDING AND 0 PRECEDING)
				WHEN ANZAHL_BIS_365 = 9 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 8 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 10 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 9 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 11 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 10 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 12 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 11 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 13 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 12 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 14 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 13 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 15 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 14 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 16 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 15 PRECEDING AND 0 PRECEDING)
				WHEN ANZAHL_BIS_365 = 17 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 16 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 18 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 17 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 19 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 18 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 20 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 19 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 21 THEN SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 20 PRECEDING AND 0 PRECEDING) 
				ELSE SUM(ZPTEM_VERBRAUCHBER) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 98 PRECEDING AND 0 PRECEDING)
			END AS PROGNOSE_ABR_365,

			CASE
				WHEN ANZAHL_BIS_365 = 1 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 0 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 2 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 1 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 3 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 2 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 4 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 3 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 5 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 4 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 6 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 5 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 7 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 6 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 8 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 7 PRECEDING AND 0 PRECEDING)
				WHEN ANZAHL_BIS_365 = 9 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 8 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 10 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 9 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 11 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 10 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 12 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 11 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 13 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 12 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 14 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 13 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 15 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 14 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 16 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 15 PRECEDING AND 0 PRECEDING)
				WHEN ANZAHL_BIS_365 = 17 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 16 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 18 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 17 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 19 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 18 PRECEDING AND 0 PRECEDING) 
				WHEN ANZAHL_BIS_365 = 20 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 19 PRECEDING AND 0 PRECEDING) 		
				WHEN ANZAHL_BIS_365 = 21 THEN SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 20 PRECEDING AND 0 PRECEDING) 
				ELSE SUM(ZPTEM_VERBRAUCHBER_NT) OVER (PARTITION BY ZPT_ID  ORDER BY ZPTEM_ZEITRAUMBIS ASC ROWS BETWEEN 98 PRECEDING AND 0 PRECEDING)
			END AS PROGNOSE_ABR_365_NT



		FROM
			jahresprognosen_gewichtet
	),
	letzte_prognose as (

		SELECT 
			ZPT_ID,
			PROG_BEGINN,
			PROG_ENDE,
			CASE WHEN PROGNOSEDATEN_TYP = 'PROG_WERT' THEN PROGNOSE_SUMME_365 ELSE PROGNOSE_ABR_365 END AS JAHRESPROGNOSE,
			CASE WHEN PROGNOSEDATEN_TYP = 'PROG_WERT' THEN PROGNOSE_SUMME_365_NT ELSE PROGNOSE_ABR_365_NT END AS JAHRESPROGNOSE_NT,
			row_number() over (partition by ZPT_ID order by PROG_ENDE desc) as rang
		FROM 
			jahresprognose_kumuliert

		)
	select
		ZPT_ID as id_zp,
		PROG_BEGINN prognose_gueltig_vom,
		PROG_ENDE prognose_gueltig_bis,
		JAHRESPROGNOSE as jahresprognose,
		JAHRESPROGNOSE as jahresprognose_nt
	from
		letzte_prognose
	where
		rang = 1


GO
