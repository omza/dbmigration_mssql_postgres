from __future__ import annotations

import pytest

from mssql2pg.convert.common import Ctx, Unsupported, translate_expr
from mssql2pg.convert.routines import convert_routine
from mssql2pg.convert.tables import convert_table
from mssql2pg.convert.views import convert_view
from mssql2pg.source import load_sources

from .conftest import FIXTURES


def _src(key):
    return next(s for s in load_sources(FIXTURES / "src", set(), []) if s.key == key)


@pytest.mark.parametrize("tsql,pg", [
    ("GETDATE()", "LOCALTIMESTAMP"),
    ("ISNULL(a, 0)", "COALESCE(a, 0)"),
    ("'a' + b + c", "'a' || b || c"),
    ("a + b", "a + b"),
    ("CAST(x AS varchar(max))", "CAST(x AS TEXT)"),
    ("CAST(x AS bit)", "CAST(x AS BOOLEAN)"),
    ("CONVERT(varchar(10), d, 104)", "CAST(TO_CHAR(d, 'DD.MM.YYYY') AS VARCHAR(10))"),
    ("CONVERT(date, '31.12.9999', 104)", "CAST('9999-12-31' AS DATE)"),
    ("STUFF(a, 1, 2, 'x')", "OVERLAY(a PLACING 'x' FROM 1 FOR 2)"),
    ("DATEFROMPARTS(2020, 1, 2)", "MAKE_DATE(2020, 1, 2)"),
    ("DATEDIFF(day, d, e)", "CAST((CAST(CAST(e AS TIMESTAMP) AS DATE) - CAST(CAST(d AS TIMESTAMP) AS DATE)) AS INT)"),
    ("TRY_CAST(a AS int)", "CASE WHEN PG_INPUT_IS_VALID(CAST(a AS TEXT), 'INT') THEN CAST(a AS INT) END"),
    ("@x + 1", "v_x + 1"),
    ("@@ROWCOUNT", "v_rowcount"),
])
def test_expressions(tsql, pg):
    ctx = Ctx(variables={"x": "v_x"}, system_vars={"rowcount": "v_rowcount"})
    assert translate_expr(tsql, ctx) == pg


def test_unknown_variable():
    with pytest.raises(Unsupported):
        translate_expr("@nope", Ctx())


def test_table():
    obj, t = convert_table(_src("core.kunde"), "localtimestamp")
    assert obj.status == "ok", obj.messages
    assert "id_kunde integer GENERATED BY DEFAULT AS IDENTITY NOT NULL" in obj.sql
    assert "name varchar(100) NOT NULL" in obj.sql
    assert "aktiv boolean DEFAULT true NOT NULL" in obj.sql
    assert "valid_to timestamp(3) DEFAULT CAST('9999-12-31 00:00:00' AS TIMESTAMP(3)) NOT NULL" in obj.sql
    assert "changed_at timestamp(3) DEFAULT LOCALTIMESTAMP" in obj.sql
    assert "CONSTRAINT pk_kunde PRIMARY KEY (id_kunde)" in obj.sql
    assert "FOREIGN KEY" not in obj.sql
    assert "REFERENCES core.gruppe (id_gruppe)" in obj.post_sql and "NOT VALID" in obj.post_sql
    assert "CREATE INDEX IF NOT EXISTS ix_kunde_name" in obj.post_sql and "INCLUDE (aktiv)" in obj.post_sql
    assert t.primary_key.columns == ["id_kunde"]
    assert t.column("aktiv").pg_type == "boolean"


def test_view():
    obj = convert_view(_src("core.kunde_gruppe"), "localtimestamp")
    assert obj.status == "ok", obj.messages
    assert obj.sql.startswith("CREATE VIEW core.kunde_gruppe AS")
    assert "'K-' || k.name AS anzeige" in obj.sql
    assert "COALESCE(g.bezeichnung, 'ohne')" in obj.sql


def test_view_top():
    obj = convert_view(_src("core.kunde_top"), "localtimestamp")
    assert "LIMIT 10" in obj.sql
    assert "FROM core.kunde_gruppe" in obj.sql


def test_procedure():
    obj = convert_routine(_src("core.load_kunde"), "localtimestamp")
    assert obj.status in ("ok", "warn"), obj.messages
    sql = obj.sql
    assert "CREATE FUNCTION core.load_kunde(" in sql
    assert "p_job_id bigint" in sql and "p_verbose smallint DEFAULT 0" in sql
    assert "RETURNS void" in sql and "LANGUAGE plpgsql" in sql
    assert "v_msg := 'core.load_kunde';" in sql
    # UPDATE alias FROM ... JOIN -> UPDATE tabelle AS alias ... FROM ... WHERE
    assert "UPDATE core.kunde AS k" in sql and "FROM core.gruppe AS g" in sql
    assert "GET DIAGNOSTICS v_rowcount = ROW_COUNT;" in sql
    assert "v_n := v_rowcount;" in sql
    assert "ELSIF p_verbose = 2 THEN" in sql and "v_n := v_n + (1);" in sql
    assert "RAISE NOTICE '%', v_msg || ': ' || CAST(v_n AS VARCHAR(10));" in sql
    assert "EXCEPTION WHEN OTHERS THEN" in sql and "v_msg := sqlerrm;" in sql
    assert "RAISE EXCEPTION '%', v_msg" in sql


def test_cursor_fails():
    obj = convert_routine(_src("core.cursor_proc"), "localtimestamp")
    assert obj.status == "failed"
    assert "Cursor" in obj.messages[0]


def test_tvf():
    obj = convert_routine(_src("core.f_split"), "localtimestamp")
    assert obj.status == "ok", obj.messages
    assert "RETURNS TABLE (teil varchar(500))" in obj.sql
    assert "#variable_conflict use_column" in obj.sql
    assert "RETURN QUERY SELECT" in obj.sql
    assert "WHILE POSITION(',' IN p_s) > 0 LOOP" in obj.sql
