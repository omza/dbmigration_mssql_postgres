"""Erzeugt die PG-SQL-Dateien für Schemas und Tabellen aus energydwh-main/.

Die erzeugten Dateien unter sql/ werden committet und reviewt. Ein erneuter Lauf
überschreibt nur Dateien, die den Marker GENERATED tragen; händisch angepasste
Dateien (Marker entfernt) bleiben unangetastet.
"""

from __future__ import annotations

from pathlib import Path

from .naming import ident
from .tables import (
    VALIDATE_FKS_SQL,
    load_tables,
    render_create,
    render_fks,
    render_identity_reset,
    render_indexes,
)

MARKER = "-- GENERATED by `energydwh generate` – Marker entfernen, um Datei manuell zu pflegen\n"

# Zusätzliche Schemas, die es nur in PG gibt
EXTRA_SCHEMAS = ["util", "_migration"]


def _write(path: Path, content: str, written: list[Path], skipped: list[Path]) -> None:
    if path.exists() and not path.read_text(encoding="utf-8").startswith(MARKER):
        skipped.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(MARKER + content, encoding="utf-8")
    written.append(path)


def collect_schemas(src: Path) -> list[str]:
    names = set()
    for p in src.rglob("*.sql"):
        names.add(p.name.split(".", 1)[0].lower())
    return sorted(names) + EXTRA_SCHEMAS


def generate(src: Path, out: Path) -> tuple[list[Path], list[Path]]:
    written: list[Path] = []
    skipped: list[Path] = []

    schemas = collect_schemas(src)
    _write(
        out / "00_bootstrap" / "01_schemas.sql",
        "".join(f"CREATE SCHEMA IF NOT EXISTS {ident(s)};\n" for s in schemas),
        written, skipped,
    )

    tables = load_tables(src / "Tables")
    for t in tables:
        _write(out / "10_tables" / f"{t.pg_schema}.{t.pg_table}.sql", render_create(t), written, skipped)

    idx = "\n".join(s for s in (render_indexes(t) for t in tables) if s)
    fks = "\n".join(s for s in (render_fks(t) for t in tables) if s)
    ids = "".join(render_identity_reset(t) for t in tables)
    _write(out / "50_post" / "01_indexes.sql", idx, written, skipped)
    _write(out / "50_post" / "02_foreign_keys.sql", fks, written, skipped)
    _write(out / "50_post" / "03_identity_reset.sql", ids, written, skipped)
    _write(out / "50_post" / "04_validate_foreign_keys.sql", VALIDATE_FKS_SQL, written, skipped)
    return written, skipped
